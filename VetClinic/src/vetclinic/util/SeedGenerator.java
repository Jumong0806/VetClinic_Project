package vetclinic.util;

import java.io.FileWriter;
import java.io.IOException;
import java.io.PrintWriter;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Random;

public class SeedGenerator {

    public static void main(String[] args) {
        String outputPath = "VetClinic/db/seed.sql";
        Random rand = new Random();
        DateTimeFormatter dateFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd");
        DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss.SSS");

        // Team Members to be seeded as Staff (S003 onwards, because S001 and S002 have been seeded)
        String[] teamNames = {
                "Dr. Rishan Pol Chadha",
                "Dr. Gabriel Lopez",
                "Dr. Jermil Madla",
                "Sean Bennedict Mariano",
                "Richnie Perez",
                "John Paul Tabafunda"
        };

        // Dummy Data Pools
        String[] firstNames = {"Juan", "Maria", "Olivia", "Nicole", "Sabrina", "Taylor", "Ethel", "Pedro"};
        String[] lastNames = {"Dela Cruz", "Gonzales", "Zefanya", "Carpenter", "Swift", "Cain", "Garcia"};
        String[] dogNames = {"Sugar", "Mochi", "Bantay", "Brownie", "Max", "Bella"};
        String[] catNames = {"Benjamin", "Mingming", "Luna", "Garfield", "Salem"};
        String[] livestockNames = {"Baka", "Kambing", "Piggy", "Chops", "Babe"};
        String[] dogBreeds = {"Shih Tzu", "Golden Retriever", "Aspin", "Pug", "Husky"};
        String[] catColors = {"Orange Tabby", "Black", "White", "Calico", "Tuxedo"};
        String[] cities = {"Apalit, Pampanga", "Malolos, Bulacan", "Guiguinto, Bulacan", "San Fernando, Pampanga"};
        String[] shifts = {"Morning", "Afternoon", "Night"};

        try (PrintWriter writer = new PrintWriter(new FileWriter(outputPath))) {
            writer.println("-- Vet Clinic Management System - demo data for MySQL.");
            writer.println("-- GENERATED by vetclinic.util.SeedGenerator.java - do not edit by hand; regenerate instead.");
            writer.println("-- Starts with staff_id S003 because S001 and S002 have been seeded.");
            writer.println("-- Every person below is synthetic (randomly combined names, numbers and addresses) for Data Privacy Act compliance.\n");

            // 1. GENERATE STAFF (Starting at S003)
            writer.println("-- staff (" + teamNames.length + " rows)");
            writer.println("INSERT INTO staff (staff_id, staff_name, contact_number, role, license_number, specialization, shift) VALUES");

            for (int i = 0; i < teamNames.length; i++) {
                String staffId = String.format("S%03d", i + 3);
                String contact = "09" + (100000000 + rand.nextInt(900000000));

                String row;
                if (i < 3) {
                    String license = "VET-2026-00" + (i + 3);
                    String spec = (i == 0) ? "Small Animals" : (i == 1) ? "Feline Specialist" : "Large Animals";
                    row = String.format("('%s', '%s', '%s', 'Veterinarian', '%s', '%s', NULL)",
                            staffId, teamNames[i], contact, license, spec);
                } else {
                    String shift = shifts[rand.nextInt(shifts.length)];
                    row = String.format("('%s', '%s', '%s', 'Vet Assistant', NULL, NULL, '%s')",
                            staffId, teamNames[i], contact, shift);
                }

                writer.print(row);
                writer.println((i == teamNames.length - 1) ? ";" : ",");
            }
            writer.println();

            // 2. GENERATE ANIMALS
            int totalAnimals = 50;
            writer.println("-- animals (" + totalAnimals + " rows)");
            writer.println("INSERT INTO animals (animal_id, species, name, age, weight_kg, owner_name, owner_contact, owner_address, registered_date, breed, rabies_vaccinated, indoor, coat_color, tag_number, livestock_type) VALUES");

            for (int i = 1; i <= totalAnimals; i++) {
                String animalId = String.format("A%03d", i);
                String ownerName = firstNames[rand.nextInt(firstNames.length)] + " " + lastNames[rand.nextInt(lastNames.length)];
                String ownerContact = "09" + (100000000 + rand.nextInt(900000000));
                String ownerAddress = cities[rand.nextInt(cities.length)];
                String regDate = LocalDate.now().minusDays(rand.nextInt(365)).format(dateFormatter);
                int age = rand.nextInt(10) + 1;
                double weight = 2.0 + (rand.nextDouble() * 20.0);

                int type = rand.nextInt(3);
                String row;

                if (type == 0) {
                    String name = dogNames[rand.nextInt(dogNames.length)];
                    String breed = dogBreeds[rand.nextInt(dogBreeds.length)];
                    boolean rabies = rand.nextBoolean();
                    row = String.format("('%s', 'Dog', '%s', %d, %.2f, '%s', '%s', '%s', '%s', '%s', %b, NULL, NULL, NULL, NULL)",
                            animalId, name, age, weight, ownerName, ownerContact, ownerAddress, regDate, breed, rabies);
                } else if (type == 1) {
                    String name = catNames[rand.nextInt(catNames.length)];
                    String color = catColors[rand.nextInt(catColors.length)];
                    boolean indoor = rand.nextBoolean();
                    row = String.format("('%s', 'Cat', '%s', %d, %.2f, '%s', '%s', '%s', '%s', NULL, NULL, %b, '%s', NULL, NULL)",
                            animalId, name, age, weight, ownerName, ownerContact, ownerAddress, regDate, indoor, color);
                } else {
                    String name = livestockNames[rand.nextInt(livestockNames.length)];
                    String tag = "TAG-" + (1000 + rand.nextInt(9000));
                    row = String.format("('%s', 'Livestock', '%s', %d, %.2f, '%s', '%s', '%s', '%s', NULL, NULL, NULL, NULL, '%s', 'Cow')",
                            animalId, name, age, weight, ownerName, ownerContact, ownerAddress, regDate, tag);
                }

                writer.print(row);
                writer.println(i == totalAnimals ? ";" : ",");
            }
            writer.println();

            // 3. GENERATE TREATMENT RECORDS (Tracking counts to match A001-T1 format)
            int totalTreatments = 80;
            writer.println("-- treatment_records (" + totalTreatments + " rows)");
            writer.println("INSERT INTO treatment_records (record_id, animal_id, treatment_date, diagnosis, treatment, medication, follow_up_date, performed_by_staff_id, created_at) VALUES");

            int[] animalTreatmentCounts = new int[totalAnimals + 1];

            for (int i = 1; i <= totalTreatments; i++) {
                int animalIndex = rand.nextInt(totalAnimals) + 1;
                animalTreatmentCounts[animalIndex]++;

                String animalId = String.format("A%03d", animalIndex);
                String recordId = animalId + "-T" + animalTreatmentCounts[animalIndex]; // Matches app runtime format

                int staffChoice = rand.nextInt(teamNames.length + 2); // 0 to 7
                String staffId;
                if (staffChoice == 0) staffId = "S001";
                else if (staffChoice == 1) staffId = "S002";
                else staffId = String.format("S%03d", staffChoice + 1);

                LocalDateTime treatTime = LocalDateTime.now().minusDays(rand.nextInt(60)).minusHours(rand.nextInt(12));
                String treatDateStr = treatTime.format(dateFormatter);
                String createdAtStr = treatTime.format(timeFormatter);

                String followUpStr = "NULL";
                if (rand.nextInt(100) < 30) {
                    followUpStr = "'" + treatTime.plusDays(rand.nextInt(14) + 1).format(dateFormatter) + "'";
                }

                String row = String.format("('%s', '%s', '%s', 'Routine Check', 'General Checkup', 'Vitamins', %s, '%s', '%s')",
                        recordId, animalId, treatDateStr, followUpStr, staffId, createdAtStr);

                writer.print(row);
                writer.println(i == totalTreatments ? ";" : ",");
            }

            System.out.println("Successfully generated " + outputPath + " flawlessly!");

        } catch (IOException e) {
            System.err.println("Failed to write seed file: " + e.getMessage());
        }
    }
}